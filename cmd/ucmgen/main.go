// ucmgen generates a strict single-byte converter from an ICU UCM file.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"log"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

var mapping = regexp.MustCompile(`^<U([0-9A-Fa-f]{1,6})>\s+\\x([0-9A-Fa-f]{2})\s+\|([013])\s*$`)

type table struct {
	decode [256]uint32
	encode map[rune]byte
}

func parse(data []byte) (table, error) {
	t := table{encode: make(map[rune]byte)}
	seenClass, seenMax, inMap, ended := false, false, false, false
	s := bufio.NewScanner(bytes.NewReader(data))
	for line := 1; s.Scan(); line++ {
		text := strings.TrimSpace(strings.SplitN(s.Text(), "#", 2)[0])
		if text == "" {
			continue
		}
		if ended {
			return t, fmt.Errorf("line %d: unexpected content after END CHARMAP", line)
		}
		if !inMap {
			if text == "CHARMAP" {
				if !seenClass || !seenMax {
					return t, fmt.Errorf("line %d: expected SBCS class and maximum byte length", line)
				}
				inMap = true
				continue
			}
			fields := strings.Fields(text)
			if len(fields) < 2 {
				return t, fmt.Errorf("line %d: invalid header", line)
			}
			switch fields[0] {
			case "<uconv_class>":
				if len(fields) != 2 || fields[1] != `"SBCS"` || seenClass {
					return t, fmt.Errorf("line %d: unsupported class", line)
				}
				seenClass = true
			case "<mb_cur_max>":
				if len(fields) != 2 || fields[1] != "1" || seenMax {
					return t, fmt.Errorf("line %d: unsupported byte length", line)
				}
				seenMax = true
			case "<code_set_name>", "<char_name_mask>", "<mb_cur_min>", "<subchar>", "<subchar1>", "<icu:charsetFamily>", "<icu:alias>":
			default:
				return t, fmt.Errorf("line %d: unsupported header %s", line, fields[0])
			}
			continue
		}
		if text == "END CHARMAP" {
			ended = true
			continue
		}
		m := mapping.FindStringSubmatch(text)
		if m == nil {
			return t, fmt.Errorf("line %d: unsupported mapping %q", line, text)
		}
		cp, _ := strconv.ParseUint(m[1], 16, 32)
		b, _ := strconv.ParseUint(m[2], 16, 8)
		r := rune(cp)
		if !utf8.ValidRune(r) {
			return t, fmt.Errorf("line %d: invalid Unicode scalar", line)
		}
		switch m[3] {
		case "0", "3":
			if t.decode[b] != 0 {
				return t, fmt.Errorf("line %d: duplicate byte mapping", line)
			}
			t.decode[b] = uint32(cp) + 1
		}
		if m[3] == "0" {
			if _, ok := t.encode[r]; ok {
				return t, fmt.Errorf("line %d: duplicate round-trip mapping", line)
			}
			t.encode[r] = byte(b)
		}
	}
	if err := s.Err(); err != nil {
		return t, err
	}
	if !ended {
		return t, fmt.Errorf("missing END CHARMAP")
	}
	return t, nil
}

func main() {
	input := flag.String("input", "", "path to an ICU UCM file")
	output := flag.String("output", "", "output Go file")
	pkg := flag.String("package", "textcodecs", "output package")
	name := flag.String("name", "", "exported Go variable name")
	flag.Parse()
	if *input == "" || *output == "" || !token.IsIdentifier(*pkg) || !token.IsIdentifier(*name) || !token.IsExported(*name) {
		log.Fatal("supply -input, -output, -package and exported -name")
	}
	data, err := os.ReadFile(*input)
	if err != nil {
		log.Fatal(err)
	}
	t, err := parse(data)
	if err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by ucmgen; DO NOT EDIT.\n// Source SHA-256: %x\npackage %s\n\n", sha256.Sum256(data), *pkg)
	if *pkg != "textcodecs" {
		log.Fatal("output package must be textcodecs")
	}
	fmt.Fprintf(&out, "var %s = SingleByte{DecodeTable: [256]uint32{\n", *name)
	for b, r := range t.decode {
		if r != 0 {
			fmt.Fprintf(&out, "%d: 0x%x,\n", b, r)
		}
	}
	fmt.Fprintln(&out, "}, EncodeTable: map[rune]byte{")
	keys := make([]int, 0, len(t.encode))
	for r := range t.encode {
		keys = append(keys, int(r))
	}
	sort.Ints(keys)
	for _, r := range keys {
		fmt.Fprintf(&out, "0x%x: 0x%x,\n", r, t.encode[rune(r)])
	}
	fmt.Fprintln(&out, "}}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*output, formatted, 0644); err != nil {
		log.Fatal(err)
	}
}
