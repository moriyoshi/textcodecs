// gensbcs generates compact built-in codecs from complete SBCS UCMs.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

var lineRE = regexp.MustCompile(`^<U([0-9A-Fa-f]{1,6})>\s+\\x([0-9A-Fa-f]{2})\s+\|([0-4])$`)

type mapping struct {
	r rune
	b byte
}
type table struct {
	decode [256]uint16
	encode []mapping
	ascii  bool
}

func parse(data []byte) (table, error) {
	var t table
	enc := map[rune]byte{}
	in, done, cls, max := false, false, false, false
	s := bufio.NewScanner(bytes.NewReader(data))
	line := 0
	for s.Scan() {
		line++
		text := strings.TrimSpace(strings.SplitN(s.Text(), "#", 2)[0])
		if text == "" {
			continue
		}
		if done {
			return t, fmt.Errorf("line %d: content after CHARMAP", line)
		}
		if !in {
			if text == "CHARMAP" {
				// ICU defaults SBCS to one byte when mb_cur_max is omitted.
				if !cls {
					return t, fmt.Errorf("line %d: missing SBCS class", line)
				}
				in = true
				continue
			}
			fields := strings.Fields(text)
			if len(fields) < 2 {
				return t, fmt.Errorf("line %d: malformed header", line)
			}
			switch fields[0] {
			case "<uconv_class>":
				if len(fields) != 2 || fields[1] != `"SBCS"` || cls {
					return t, fmt.Errorf("line %d: wrong class", line)
				}
				cls = true
			case "<mb_cur_max>":
				if len(fields) != 2 || fields[1] != "1" || max {
					return t, fmt.Errorf("line %d: wrong width", line)
				}
				max = true
			case "<code_set_name>", "<char_name_mask>", "<mb_cur_min>", "<subchar>", "<subchar1>", "<icu:charsetFamily>", "<icu:alias>":
			default:
				return t, fmt.Errorf("line %d: unsupported header %s", line, fields[0])
			}
			continue
		}
		if text == "END CHARMAP" {
			done = true
			continue
		}
		m := lineRE.FindStringSubmatch(text)
		if m == nil {
			return t, fmt.Errorf("line %d: unsupported mapping %q", line, text)
		}
		u, _ := strconv.ParseUint(m[1], 16, 32)
		v, _ := strconv.ParseUint(m[2], 16, 8)
		r := rune(u)
		b := byte(v)
		if !utf8.ValidRune(r) || r >= 0xffff {
			return t, fmt.Errorf("line %d: unsupported Unicode scalar", line)
		}
		if m[3] == "0" || m[3] == "3" {
			if t.decode[b] != 0 {
				return t, fmt.Errorf("line %d: duplicate decode", line)
			}
			t.decode[b] = uint16(r) + 1
		}
		if m[3] == "0" || m[3] == "4" || (m[3] == "1" && r >= 0xe000 && r <= 0xf8ff) {
			if _, ok := enc[r]; ok {
				return t, fmt.Errorf("line %d: duplicate encode", line)
			}
			enc[r] = b
		}
	}
	if err := s.Err(); err != nil {
		return t, err
	}
	if !done {
		return t, fmt.Errorf("missing END CHARMAP")
	}
	for r, b := range enc {
		t.encode = append(t.encode, mapping{r, b})
	}
	sort.Slice(t.encode, func(i, j int) bool { return t.encode[i].r < t.encode[j].r })
	t.ascii = true
	for i := 0; i < 128; i++ {
		b, ok := enc[rune(i)]
		if t.decode[i] != uint16(i+1) || !ok || int(b) != i {
			t.ascii = false
			break
		}
	}
	return t, nil
}

func main() {
	dir := flag.String("input", "data/icu/mappings", "directory containing UCM files")
	out := flag.String("output", "data/icu/sbcs.dat", "binary output")
	metadata := flag.String("metadata", "sbcs_generated.go", "Go registry output")
	manifest := flag.String("manifest", "data/icu/sbcs.sha256", "source hashes output")
	kanaDir := flag.String("ebcdic-kana", "data/ebcdic-kana", "ebcdic-kana UCM directory (empty to omit)")
	phpList := flag.String("php-list", "data/php-mbstring/registry-sbcs.txt", "selected PHP mappings (empty to omit)")
	flag.Parse()
	files, err := filepath.Glob(filepath.Join(*dir, "*.ucm"))
	if err != nil || len(files) == 0 {
		log.Fatal("no UCM files found")
	}
	kanaFiles := map[string]bool{}
	phpFiles := map[string]bool{}
	if *phpList != "" {
		list, err := os.ReadFile(*phpList)
		if err != nil {
			log.Fatal(err)
		}
		for _, name := range strings.Fields(string(list)) {
			if filepath.Base(name) != name || !strings.HasSuffix(name, ".ucm") {
				log.Fatalf("invalid PHP mapping %q", name)
			}
			path := filepath.Join(filepath.Dir(*phpList), name)
			phpFiles[path] = true
			files = append(files, path)
		}
	}
	if *kanaDir != "" {
		inputs, err := filepath.Glob(filepath.Join(*kanaDir, "*.ucm"))
		if err != nil || len(inputs) == 0 {
			log.Fatal("no ebcdic-kana UCM files found")
		}
		for _, path := range inputs {
			kanaFiles[path] = true
		}
		files = append(files, inputs...)
	}
	sort.Slice(files, func(i, j int) bool {
		a := strings.TrimSuffix(filepath.Base(files[i]), ".ucm")
		b := strings.TrimSuffix(filepath.Base(files[j]), ".ucm")
		return strings.ToLower(a) < strings.ToLower(b)
	})
	var data, goSrc, hashes bytes.Buffer
	names := map[string]bool{}
	fmt.Fprintln(&goSrc, "// Code generated by cmd/gensbcs; DO NOT EDIT.\npackage textcodecs\n\nvar sbcsEntries = [...]sbcsEntry{")
	for _, path := range files {
		raw, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		t, err := parse(raw)
		if err != nil {
			log.Fatalf("%s: %v", path, err)
		}
		name := strings.TrimSuffix(filepath.Base(path), ".ucm")
		if names[strings.ToLower(name)] {
			log.Fatalf("duplicate converter name %s", name)
		}
		names[strings.ToLower(name)] = true
		offset := data.Len()
		for _, v := range t.decode {
			if err := binary.Write(&data, binary.LittleEndian, v); err != nil {
				log.Fatal(err)
			}
		}
		for _, e := range t.encode {
			if err := binary.Write(&data, binary.LittleEndian, uint16(e.r)); err != nil {
				log.Fatal(err)
			}
			data.WriteByte(e.b)
		}
		fmt.Fprintf(&goSrc, "{name:%q, offset:%d, count:%d, ascii:%t},\n", name, offset, len(t.encode), t.ascii)
		if !kanaFiles[path] && !phpFiles[path] {
			fmt.Fprintf(&hashes, "%x  %s\n", sha256.Sum256(raw), filepath.Base(path))
		}
	}
	fmt.Fprintln(&goSrc, "}")
	formatted, err := format.Source(goSrc.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	for _, o := range []struct {
		path string
		data []byte
	}{{*out, data.Bytes()}, {*metadata, formatted}, {*manifest, hashes.Bytes()}} {
		if err := os.WriteFile(o.path, o.data, 0644); err != nil {
			log.Fatal(err)
		}
	}
	fmt.Fprintf(os.Stderr, "%d converters, %d table bytes\n", len(files), data.Len())
}
