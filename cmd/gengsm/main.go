// gengsm generates the GSM 03.38 single-byte and escape-extension tables.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"
)

var mapping = regexp.MustCompile(`^<U([0-9A-Fa-f]{1,6})>\s+\\x([0-9A-Fa-f]{2})(?:\\x([0-9A-Fa-f]{2}))?\s+\|([0-4])$`)

func main() {
	in := flag.String("input", "data/icu/gsm-03.38-2009.ucm", "source UCM")
	out := flag.String("output", "gsm_generated.go", "Go output")
	flag.Parse()
	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	const expected = "e53e04bb4a022713276ff63702fd404681f70288b43eab14e467636a9c5edcba"
	if fmt.Sprintf("%x", sha256.Sum256(raw)) != expected {
		log.Fatal("unexpected GSM source hash")
	}
	var single, ext [128]uint16
	enc := map[rune]uint16{}
	scanner := bufio.NewScanner(bytes.NewReader(raw))
	inMap, done := false, false
	line := 0
	for scanner.Scan() {
		line++
		text := strings.TrimSpace(strings.SplitN(scanner.Text(), "#", 2)[0])
		if text == "" {
			continue
		}
		if text == "CHARMAP" {
			if inMap || done {
				log.Fatal("multiple maps")
			}
			inMap = true
			continue
		}
		if text == "END CHARMAP" {
			inMap = false
			done = true
			continue
		}
		if !inMap {
			continue
		}
		m := mapping.FindStringSubmatch(text)
		if m == nil {
			log.Fatalf("line %d: unsupported mapping %q", line, text)
		}
		r64, _ := strconv.ParseUint(m[1], 16, 32)
		r := rune(r64)
		a, _ := strconv.ParseUint(m[2], 16, 8)
		two := m[3] != ""
		b := uint64(0)
		if two {
			b, _ = strconv.ParseUint(m[3], 16, 8)
		}
		if !utf8.ValidRune(r) || r >= 0xffff || a >= 128 || b >= 128 || two && a != 0x1b {
			log.Fatalf("line %d: unsupported mapping", line)
		}
		if m[4] == "0" || m[4] == "3" {
			if two {
				if ext[b] != 0 {
					log.Fatal("duplicate extension")
				}
				ext[b] = uint16(r) + 1
			} else {
				if single[a] != 0 {
					log.Fatal("duplicate byte")
				}
				single[a] = uint16(r) + 1
			}
		}
		if m[4] == "0" || m[4] == "4" || (m[4] == "1" && r >= 0xe000 && r <= 0xf8ff) {
			if _, ok := enc[r]; ok {
				log.Fatal("duplicate scalar")
			}
			v := uint16(a)
			if two {
				v = 0x1b00 | uint16(b)
			}
			enc[r] = v + 1
		}
	}
	if err := scanner.Err(); err != nil {
		log.Fatal(err)
	}
	if !done {
		log.Fatal("missing end CHARMAP")
	}
	var dst bytes.Buffer
	fmt.Fprintf(&dst, "// Code generated by cmd/gengsm; DO NOT EDIT.\n// UCM SHA-256: %x\npackage textcodecs\n", sha256.Sum256(raw))
	for _, v := range []struct {
		name  string
		table [128]uint16
	}{{"gsmSingle", single}, {"gsmExtension", ext}} {
		fmt.Fprintf(&dst, "var %s = [128]uint16{\n", v.name)
		for i, x := range v.table {
			if x != 0 {
				fmt.Fprintf(&dst, "%d:%d,\n", i, x)
			}
		}
		fmt.Fprintln(&dst, "}")
	}
	keys := make([]int, 0, len(enc))
	for r := range enc {
		keys = append(keys, int(r))
	}
	sort.Ints(keys)
	fmt.Fprintln(&dst, "var gsmEncode = [...]gsmMapping{")
	for _, r := range keys {
		fmt.Fprintf(&dst, "{r:%d,code:%d},\n", r, enc[rune(r)])
	}
	fmt.Fprintln(&dst, "}")
	code, err := format.Source(dst.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0644); err != nil {
		log.Fatal(err)
	}
}
